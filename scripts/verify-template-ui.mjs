import { chromium } from 'playwright-core';
import { mkdir, writeFile } from 'node:fs/promises';
import { randomBytes } from 'node:crypto';
import assert from 'node:assert/strict';
const origin=process.argv[2]||'http://127.0.0.1:4187';
const out=process.argv[3]||'outputs/template-upload';
await mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1050}});
const username='upload_qa_'+Date.now(),password=randomBytes(18).toString('hex');
const registered=await context.request.post(origin+'/api/auth/register',{headers:{Origin:origin},data:{username,password}});
assert.equal(registered.status(),201);
const account=await registered.json();
const page=await context.newPage(),errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
  await page.goto(origin);
  await page.getByRole('button',{name:'发布中心',exact:true}).click();
  await page.getByRole('button',{name:'上传图片',exact:true}).waitFor();
  await page.screenshot({path:out+'/upload-desktop-empty.png',fullPage:true});
  const imagePage=await context.newPage();
  await imagePage.setContent('<html><body style="margin:0;background:#ecf5f1"><canvas width="1000" height="900"></canvas></body></html>');
  await imagePage.evaluate(()=>{const c=document.querySelector('canvas'),x=c.getContext('2d');const d=x.createImageData(c.width,c.height);for(let i=0;i<d.data.length;i+=4){d.data[i]=(i*13)%255;d.data[i+1]=Math.random()*255;d.data[i+2]=Math.random()*255;d.data[i+3]=255;}x.putImageData(d,0,0);});
  const buffer=await imagePage.locator('canvas').screenshot();
  assert(buffer.length>2*1024*1024,'verify upload exceeds the previous 2 MB request limit');
  await imagePage.close();
  const file={name:'本地上传验收（中文）.png',mimeType:'image/png',buffer};
  const chooserPromise=page.waitForEvent('filechooser');
  await page.getByRole('button',{name:'上传图片',exact:true}).click();
  await (await chooserPromise).setFiles([file]);
  await page.getByRole('checkbox',{name:'选择 本地上传验收（中文）',exact:true}).waitFor({timeout:60000});
  await page.waitForFunction(()=>[...document.querySelectorAll('.asset-preview img')].every(i=>i.complete&&i.naturalWidth>0));
  const items=(await (await context.request.get(origin+'/api/templates/mine')).json()).items;
  assert.equal(items.length,1);
  await page.getByLabel('本地图片文件').setInputFiles([file]);
  await page.getByText('已在素材库',{exact:true}).waitFor({timeout:60000});
  assert.equal((await (await context.request.get(origin+'/api/templates/mine')).json()).items.length,1);
  await page.screenshot({path:out+'/upload-desktop-saved.png',fullPage:true});
  await page.getByRole('checkbox',{name:'选择 本地上传验收（中文）',exact:true}).check();
  await page.getByRole('button',{name:'使用所选图片',exact:true}).click();
  await page.waitForFunction(()=>[...document.querySelectorAll('[role=tab]')].some(t=>t.textContent==='素材二创'&&t.getAttribute('aria-selected')==='true'));
  await page.getByLabel('选题',{exact:true}).fill('独立文案：桌面整理');
  await page.getByRole('tab',{name:'模板素材库',exact:true}).click();
  await page.getByRole('tab',{name:'图文创作',exact:true}).click();
  assert.equal(await page.getByLabel('选题',{exact:true}).inputValue(),'独立文案：桌面整理');
  await page.reload();await page.getByRole('button',{name:'发布中心',exact:true}).click();
  await page.getByRole('checkbox',{name:'选择 本地上传验收（中文）',exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>[...document.querySelectorAll('.asset-preview img')].every(i=>i.complete&&i.naturalWidth>0));
  await page.screenshot({path:out+'/upload-mobile.png',fullPage:true});
  const overflow=await page.locator('.personal-library').evaluate(e=>e.scrollWidth-e.clientWidth);
  assert(overflow<=2,'library must not overflow on mobile');
  await page.getByRole('button',{name:'预览 本地上传验收（中文）',exact:true}).click();
  await page.getByRole('dialog',{name:'图片预览'}).waitFor();
  await page.getByRole('button',{name:'关闭预览'}).click();
  page.on('dialog',d=>d.accept());
  await page.getByRole('button',{name:'删除 本地上传验收（中文）',exact:true}).click();
  await page.getByText('还没有图片素材',{exact:true}).waitFor();
  assert.equal(errors.length,0,JSON.stringify(errors));
  const report={origin,username,tenant:account.workspace,uploadBytes:buffer.length,visibleButton:true,fileChooser:true,persisted:true,duplicatePrevented:true,selectedForCreation:true,draftPreserved:true,thumbnail:true,mobileOverflow:overflow,delete:true,consoleErrors:errors};
  await writeFile(out+'/report.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report));
}finally{await browser.close();}
