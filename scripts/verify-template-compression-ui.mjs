import {chromium} from 'playwright-core';
import sharp from 'sharp';
import {randomBytes} from 'node:crypto';
import {mkdir,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const origin=process.env.VERIFY_ORIGIN||process.env.PUBLIC_ORIGIN;if(!origin)throw new Error('请设置 VERIFY_ORIGIN 或 PUBLIC_ORIGIN');const out='outputs/template-speed';await mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
try{
 const context=await browser.newContext();
 const username='speed_qa_'+Date.now();
 const registered=await context.request.post(origin+'/api/auth/register',{headers:{Origin:origin},data:{username,password:randomBytes(20).toString('hex')}});
 assert.equal(registered.status(),201);const account=await registered.json();
 await writeFile(out+'/test-account.json',JSON.stringify({username,tenant:account.workspace}));
 const page=await context.newPage();await page.goto(origin);await page.getByRole('button',{name:'发布中心',exact:true}).click();
 const buffer=await sharp(randomBytes(4000*3000*3),{raw:{width:4000,height:3000,channels:3}}).jpeg({quality:92}).toBuffer();
 const start=Date.now(),uploaded=page.waitForResponse(r=>r.url().endsWith('/api/templates/upload')&&r.request().method()==='POST');
 await page.getByLabel('本地图片文件').setInputFiles({name:'上传速度验收.jpg',mimeType:'image/jpeg',buffer});
 const result=await uploaded;assert.equal(result.status(),201);const {item}=await result.json();
 await page.waitForFunction(()=>{const i=document.querySelector('.asset-preview img');return i?.complete&&i.naturalWidth>0;});
 const shownMs=Date.now()-start;
 const card=await page.locator('.asset-preview img').evaluate(i=>({src:i.getAttribute('src'),width:i.naturalWidth}));
 assert(card.src.endsWith('?size=thumb'));assert(card.width<=480);
 const saved=await context.request.get(origin+item.images[0]);const bytes=await saved.body();assert(bytes.length<buffer.length*0.5);
 const meta=await sharp(bytes).metadata();assert(Math.max(meta.width,meta.height)<=2560);
 await page.getByRole('button',{name:'预览 上传速度验收',exact:true}).click();
 await page.waitForFunction(()=>{const i=document.querySelector('.asset-modal img');return i?.complete&&i.naturalWidth>0;});
 await page.screenshot({path:out+'/preview.png'});
 await page.getByRole('button',{name:'关闭预览'}).click();
 await page.screenshot({path:out+'/library.png'});
 const removed=await context.request.post(origin+'/api/templates/bulk-delete',{headers:{Origin:origin},data:{ids:[item.id]}});assert.equal(removed.status(),200);
 const report={username,tenant:account.workspace,originalBytes:buffer.length,uploadedBytes:bytes.length,card,shownMs,preview:true,testImageDeleted:true};
 await writeFile(out+'/browser-report.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report));
}finally{await browser.close();}
